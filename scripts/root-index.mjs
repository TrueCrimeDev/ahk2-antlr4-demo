// Writes a root index.html that loads the build from docs/, so the site works
// whether GitHub Pages serves the repository root or the docs folder.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

let html = readFileSync('docs/index.html', 'utf8');
const assets = readdirSync('docs').filter(f => f !== 'index.html');
const escape = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
for (const name of assets) {
    // Parcel minifies attributes, so values may be quoted or bare, with or without "./".
    const re = new RegExp(`(\\b(?:src|href)=)(["']?)(?:\\./)?${escape(name)}\\2`, 'g');
    html = html.replace(re, `$1$2docs/${name}$2`);
}
const note = '<!-- Generated by "npm run build" from src/index.html. Edit that file instead. -->\n';
writeFileSync('index.html', html.replace(/^(<!doctype html>)/i, `$1\n${note}`));
console.log(`Wrote index.html for the repository root (${assets.length} assets)`);
